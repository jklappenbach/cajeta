#!/usr/bin/env python3
"""Generate the toolchain/compile-10k program (bench/toolchain/Compile.md) in
Cajeta, Java, Rust, Go, C++ and Python, from one description.

    gen_synth.py <dir> [--classes N]

Writes <dir>/synth-10k/<lang>/ for each language plus <dir>/synth-10k/EXPECTED
(the line every build of the program must print) and LINES (the Cajeta line
count). Deterministic: every constant comes from a fixed-seed xorshift64, so
two runs write the same bytes, and an existing tree whose STAMP matches this
script's digest is reused untouched.

The description (one model, six renderings):
  * an interface `Stage { int64 apply(int64 v) }`;
  * N = 200 classes C000..C199, each in its own file, each implementing Stage
    with three int64 fields, a constructor, and six methods (step: an
    8-iteration loop; mix: a branch; fold: a 6-iteration loop over a field;
    twist: a call into step and mix; count; apply: the Stage method composing
    the others) and per-class constants;
  * Main: puts one instance of every class into a list of Stage (dynamic
    dispatch), runs ROUNDS passes over it, then calls every class's fold
    through its static type, and prints `synth <checksum> <calls>`.
All arithmetic is modulo M = 1000003 with operands below 2^20, so no product
exceeds 2^41: no language overflows and Python's integers agree bit for bit.
The Cajeta rendering is 10,000 lines +-2% at N=200 (LINES records it).
"""
import hashlib
import os
import sys

M = 1000003
ROUNDS = 4


def xorshift(seed):
    x = seed & 0xFFFFFFFFFFFFFFFF
    while True:
        x ^= (x << 13) & 0xFFFFFFFFFFFFFFFF
        x ^= x >> 7
        x ^= (x << 17) & 0xFFFFFFFFFFFFFFFF
        yield x


class Model:
    def __init__(self, n):
        rng = xorshift(0x5EED_C0DE_2026_1025)
        self.n = n
        self.k = []   # per class: (A, B, C, D, seed)
        for _ in range(n):
            a = next(rng) % 900000 + 3
            b = next(rng) % 1000000 + 1
            c = next(rng) % 1000000 + 1
            d = next(rng) % 97 + 2
            s = next(rng) % 1000 + 1
            self.k.append((a, b, c, d, s))

    # --- the reference semantics (Python), used for EXPECTED ---------------
    def run(self):
        objs = [Obj(self.k[i]) for i in range(self.n)]
        v = 1
        for _ in range(ROUNDS):
            for o in objs:
                v = o.apply(v)
        for i in range(self.n):
            d = Obj(self.k[i])
            v = (v + d.fold(v + i)) % M
        calls = sum(o.calls for o in objs)
        return "synth %d %d" % (v, calls)


class Obj:
    def __init__(self, k):
        self.A, self.B, self.C, self.D, seed = k
        self.x = (seed * self.A + self.B) % M
        self.y = (seed * self.D + self.C) % M
        self.calls = 0

    def step(self, v):
        r = v
        i = 0
        while i < 8:
            r = (r * self.A + self.B + i) % M
            i += 1
        return r

    def mix(self, v, w):
        if v > w:
            return (v - w + self.C) % M
        return (w - v + self.A) % M

    def fold(self, v):
        r = 0
        i = 0
        while i < 6:
            r = (r + (v % 1024) * (i + 1) + self.x) % M
            i += 1
        return r

    def twist(self, v):
        return self.mix(self.step(v), self.y)

    def count(self):
        self.calls += 1
        return self.calls

    def apply(self, v):
        self.count()
        t = self.twist(v)
        return (self.mix(t, self.fold(t)) * self.D + self.x) % M


