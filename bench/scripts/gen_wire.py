#!/usr/bin/env python3
"""One description of the wire/ benchmarks' 100-field record (bench/wire/*.md,
benchmark-reference unit 13), and every schema and Cajeta source made from it.

The record: fields f1..f100, field number k = protobuf field number k.
    k % 5 == 0  float64   v = r * 0.5 + k * 0.25
    k % 5 == 1  int32     v = (r * 31 + k * 17) % 65536
    otherwise   int64     v = (r + 1) * (k*k*k + 17)
(20 float64, 20 int32, 60 int64; no value is ever zero, so no format elides a
field as a default.) Record r of a run is pool record r % 1024.

Checksum of a record: the sum of its integer fields plus, for each float64
field, (int64)(v * 4) (exact: every v is a multiple of 0.25).

Workloads (N = 1e6 encodes/decodes; smoke 1e5; M = 1e6 view records; smoke 1e5):
    encoder-encode         for i < N: bytes = encode(pool[i % 1024]); total += len
    encoder-decode         for i < N: rec = decode(enc[i % 1024]); sum += checksum(rec)
    struct-view-read       M records in the fixed layout (u32 count, then each
                           record's fields in order, little-endian, int32 = 4
                           bytes, int64/float64 = 8: 720 bytes), read f1, f2, f5:
                           sum += f1 + f2 + (int64)(f5 * 4)
    schemaencoder-*        the same as encoder-*, Avro binary under record.avsc
    compressstream-roundtrip  64 MiB (smoke 8 MiB) = the fixed layout of records
                           0, 1, 2, ... (no count prefix) cut at the size; written
                           in 64 KiB pieces, sync-flushed every 1 MiB, finished,
                           then decompressed and compared byte for byte.

Writes (relative to the bench/ directory given as argv[1], default ..):
    src/main/cajeta/bench/wire/WireRecord.cajeta      the class, fill, fixed layout
    src/main/cajeta/bench/wire/WireRecordPb.cajeta    Encoder<WireRecord> (protobuf wire format)
    src/main/cajeta/bench/wire/WireRecordAvro.cajeta  SchemaEncoder<WireRecord> (Avro binary)
    src/main/cajeta/bench/wire/WireRecordView.cajeta  the zero-copy views
    src/main/cajeta/bench/wire/WireExpect.cajeta      the expected constants below
    competitors/cpp/wire/schema/record.{proto,fbs,capnp,avsc}, expect.tsv
and prints the constants.
"""
import os
import struct
import sys

POOL = 1024
K = range(1, 101)


def kind(k):
    if k % 5 == 0:
        return "f64"
    if k % 5 == 1:
        return "i32"
    return "i64"


def value(r, k):
    t = kind(k)
    if t == "f64":
        return r * 0.5 + k * 0.25
    if t == "i32":
        return (r * 31 + k * 17) % 65536
    return (r + 1) * (k * k * k + 17)


def varint_len(v):
    n = 1
    while v >= 0x80:
        v >>= 7
        n += 1
    return n


def pb_size(r):
    s = 0
    for k in K:
        s += varint_len(k << 3)
        s += 8 if kind(k) == "f64" else varint_len(value(r, k))
    return s


def avro_size(r):
    s = 0
    for k in K:
        s += 8 if kind(k) == "f64" else varint_len(value(r, k) * 2)   # zigzag of v >= 0
    return s


def checksum(r):
    s = 0
    for k in K:
        v = value(r, k)
        s += int(v * 4) if kind(k) == "f64" else v
    return s


def view_sum(r):
    return value(r, 1) + value(r, 2) + int(value(r, 5) * 4)


FIXED = sum(4 if kind(k) == "i32" else 8 for k in K)


def fixed_bytes(r):
    out = bytearray()
    for k in K:
        t = kind(k)
        v = value(r, k)
        out += struct.pack("<d", v) if t == "f64" else struct.pack("<i" if t == "i32" else "<q", v)
    return bytes(out)


def stream_data(size):
    out = bytearray()
    r = 0
    while len(out) < size:
        out += fixed_bytes(r % POOL)
        r += 1
    return bytes(out[:size])


def constants():
    pbs = [pb_size(r) for r in range(POOL)]
    avs = [avro_size(r) for r in range(POOL)]
    cks = [checksum(r) for r in range(POOL)]
    vs = [view_sum(r) for r in range(POOL)]
    c = {"fixed_record_bytes": FIXED}
    for tag, n in (("full", 1000000), ("smoke", 100000)):
        c[f"pb_total_{tag}"] = sum(pbs[i % POOL] for i in range(n))
        c[f"avro_total_{tag}"] = sum(avs[i % POOL] for i in range(n))
        c[f"decode_sum_{tag}"] = sum(cks[i % POOL] for i in range(n))
        c[f"view_sum_{tag}"] = sum(vs[i % POOL] for i in range(n))
    import zlib
    for tag, size in (("full", 64 << 20), ("smoke", 8 << 20)):
        c[f"stream_bytes_{tag}"] = size
        c[f"stream_crc32_{tag}"] = zlib.crc32(stream_data(size))
    return c


def cj_type(k):
    return {"f64": "float64", "i32": "int32", "i64": "int64"}[kind(k)]


def gen_record():
    L = []
    w = L.append
    w("package bench.wire;")
    w("")
    w("// GENERATED by bench/scripts/gen_wire.py: do not edit. The wire/ benchmarks'")
    w("// 100-field record (f1..f100; k % 5 == 0 float64, k % 5 == 1 int32, else int64),")
    w("// the pool record r's values, its checksum and its fixed little-endian layout.")
    w("public final class WireRecord {")
    for k in K:
        w(f"    public {cj_type(k)} f{k};")
    w("")
    w("    public WireRecord() {")
    for k in K:
        z = "0.0" if kind(k) == "f64" else "0"
        w(f"        this.f{k} = {z};")
    w("    }")
    w("")
    w("    // Pool record r (0 <= r < 1024).")
    w("    public static #WireRecord fill(int32 r) {")
    w("        WireRecord o = heap WireRecord();")
    w("        int64 r1 = (int64) r + 1;")
    w("        float64 rh = (float64) r * 0.5;")
    for k in K:
        t = kind(k)
        if t == "f64":
            w(f"        o.f{k} = rh + {k * 0.25!r};")
        elif t == "i32":
            w(f"        o.f{k} = (r * 31 + {k * 17}) % 65536;")
        else:
            w(f"        o.f{k} = r1 * (int64) {k * k * k + 17};")
    w("        return #o;")
    w("    }")
    w("")
    w("    // Integer fields summed, plus (int64)(v * 4) of each float64 field.")
    w("    public int64 checksum() {")
    w("        int64 s = 0;")
    for k in K:
        t = kind(k)
        if t == "f64":
            w(f"        s = s + (int64) (this.f{k} * 4.0);")
        elif t == "i32":
            w(f"        s = s + (int64) this.f{k};")
        else:
            w(f"        s = s + this.f{k};")
    w("        return s;")
    w("    }")
    w("")
    w(f"    // The fixed layout ({FIXED} bytes): fields in order, little-endian, int32 = 4")
    w("    // bytes, int64 and float64 = 8. Writes at dst[off ..); returns off + 720.")
    w("    public int64 writeFixed(int8[] dst, int64 off) {")
    off = 0
    for k in K:
        t = kind(k)
        if t == "i32":
            w(f"        WireRecord.put32(dst, off + {off}, this.f{k});")
            off += 4
        elif t == "i64":
            w(f"        Cajeta.storeU64(dst, off + {off}, this.f{k});")
            off += 8
        else:
            w(f"        Cajeta.storeU64(dst, off + {off}, Cajeta.f64ToBits(this.f{k}));")
            off += 8
    w(f"        return off + {off};")
    w("    }")
    w("")
    w("    static void put32(int8[] dst, int64 off, int32 v) {")
    w("        dst[off] = (int8) (v & 255);")
    w("        dst[off + 1] = (int8) ((v >> 8) & 255);")
    w("        dst[off + 2] = (int8) ((v >> 16) & 255);")
    w("        dst[off + 3] = (int8) ((v >> 24) & 255);")
    w("    }")
    w("}")
    return "\n".join(L) + "\n"


def gen_pb():
    L = []
    w = L.append
    w("package bench.wire;")
    w("")
    w("import cajeta.wire.Encoder;")
    w("")
    w("// GENERATED by bench/scripts/gen_wire.py: do not edit. Encoder<WireRecord> in the")
    w("// protobuf wire format (proto3, record.proto): each field as tag (k << 3 | wire")
    w("// type) then a varint (int32, int64: wire type 0) or 8 little-endian bytes")
    w("// (double: wire type 1), in field order, so the bytes equal protobuf's own")
    w("// serialization of the same message. encode sizes the message first and fills")
    w("// one exact buffer; decode reads tags in any order (last one wins, as protobuf")
    w("// does) into a scratch slot per field number, then assigns the fields.")
    w("public final class WireRecordPb implements Encoder<WireRecord> {")
    w("    int64[] slots;")
    w("")
    w("    public WireRecordPb() {")
    w("        this.slots = heap int64[101];")
    w("    }")
    w("")
    w("    static int32 vlen(int64 v) {")
    w("        int32 n = 1;")
    w("        int64 x = v;")
    w("        while (x >= (int64) 128) {")
    w("            x = x >> 7;")
    w("            n = n + 1;")
    w("        }")
    w("        return n;")
    w("    }")
    w("")
    w("    static int32 putVar(int8[] b, int32 p, int64 v) {")
    w("        int32 o = p;")
    w("        int64 x = v;")
    w("        while (x >= (int64) 128) {")
    w("            b[o] = (int8) ((x & (int64) 127) | (int64) 128);")
    w("            x = x >> 7;")
    w("            o = o + 1;")
    w("        }")
    w("        b[o] = (int8) x;")
    w("        return o + 1;")
    w("    }")
    w("")
    w("    public int32 size(WireRecord v) {")
    fixed_part = sum(varint_len(k << 3) for k in K) + 8 * sum(1 for k in K if kind(k) == "f64")
    w(f"        int32 s = {fixed_part};")
    for k in K:
        t = kind(k)
        if t == "i32":
            w(f"        s = s + WireRecordPb.vlen((int64) v.f{k});")
        elif t == "i64":
            w(f"        s = s + WireRecordPb.vlen(v.f{k});")
    w("        return s;")
    w("    }")
    w("")
    w("    public #int8[] encode(WireRecord v) {")
    w("        int8[] b = heap int8[this.size(v)];")
    w("        int32 p = 0;")
    for k in K:
        t = kind(k)
        tag = (k << 3) | (1 if t == "f64" else 0)
        if tag < 128:
            w(f"        b[p] = (int8) {tag};")
            w("        p = p + 1;")
        else:
            w(f"        b[p] = (int8) {(tag & 127) | 128};")
            w(f"        b[p + 1] = (int8) {tag >> 7};")
            w("        p = p + 2;")
        if t == "f64":
            w(f"        Cajeta.storeU64(b, (int64) p, Cajeta.f64ToBits(v.f{k}));")
            w("        p = p + 8;")
        elif t == "i32":
            w(f"        p = WireRecordPb.putVar(b, p, (int64) v.f{k});")
        else:
            w(f"        p = WireRecordPb.putVar(b, p, v.f{k});")
    w("        return #b;")
    w("    }")
    w("")
    w("    public #WireRecord decode(int8[] bytes) {")
    w("        int64[] s = this.slots;")
    w("        int32 n = (int32) bytes.count();")
    w("        int32 p = 0;")
    w("        while (p < n) {")
    w("            int64 tag = 0;")
    w("            int32 sh = 0;")
    w("            int64 c = (int64) 128;")
    w("            while (c >= (int64) 128) {")
    w("                c = ((int64) bytes[p]) & (int64) 255;")
    w("                tag = tag | ((c & (int64) 127) << sh);")
    w("                sh = sh + 7;")
    w("                p = p + 1;")
    w("            }")
    w("            int32 field = (int32) (tag >> 3);")
    w("            if ((tag & (int64) 7) == (int64) 1) {")
    w("                s[field] = Cajeta.loadU64(bytes, (int64) p);")
    w("                p = p + 8;")
    w("            } else {")
    w("                int64 v = 0;")
    w("                int32 vs = 0;")
    w("                int64 d = (int64) 128;")
    w("                while (d >= (int64) 128) {")
    w("                    d = ((int64) bytes[p]) & (int64) 255;")
    w("                    v = v | ((d & (int64) 127) << vs);")
    w("                    vs = vs + 7;")
    w("                    p = p + 1;")
    w("                }")
    w("                s[field] = v;")
    w("            }")
    w("        }")
    w("        WireRecord o = heap WireRecord();")
    for k in K:
        t = kind(k)
        if t == "f64":
            w(f"        o.f{k} = Cajeta.bitsToF64(s[{k}]);")
        elif t == "i32":
            w(f"        o.f{k} = (int32) s[{k}];")
        else:
            w(f"        o.f{k} = s[{k}];")
    w("        return #o;")
    w("    }")
    w("}")
    return "\n".join(L) + "\n"


def avsc():
    fields = ",\n".join(
        f'    {{"name": "f{k}", "type": "{ {"f64": "double", "i32": "int", "i64": "long"}[kind(k)] }"}}' for k in K)
    return '{\n  "type": "record", "name": "WireRecord", "namespace": "bench.wire",\n  "fields": [\n' + fields + "\n  ]\n}\n"


def gen_avro():
    schema = avsc().replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n")
    kinds = "".join({"f64": "d", "i32": "i", "i64": "l"}[kind(k)] for k in K)
    L = []
    w = L.append
    w("package bench.wire;")
    w("")
    w("import cajeta.error.Exception;")
    w("import cajeta.wire.Schema;")
    w("import cajeta.wire.SchemaEncoder;")
    w("")
    w("// GENERATED by bench/scripts/gen_wire.py: do not edit. SchemaEncoder<WireRecord>")
    w("// in Avro binary encoding (record.avsc): fields in schema order with no tags,")
    w("// int and long as zigzag varints, double as 8 little-endian bytes. The")
    w("// encoder resolves a Schema the first time it sees it: it reads the field")
    w("// types out of the definition (the record.avsc JSON text) and refuses a")
    w("// schema whose field types differ from the compiled layout, then encodes")
    w("// with the generated writer (the way Avro's generated SpecificRecord code")
    w("// does). cajeta.wire.Schema is an opaque carrier in v1, so the resolve is a")
    w("// scan of the JSON for \"type\" values, not a full Avro schema parser.")
    w("public final class WireRecordAvro implements SchemaEncoder<WireRecord> {")
    w(f"    // The field types in order: d = double, i = int, l = long.")
    w("    public static #String kinds() {")
    w(f"        return \"\" + \"{kinds}\";")
    w("    }")
    w("    int8[] resolved;")
    w("    int32 resolvedLen;")
    w("")
    w("    public WireRecordAvro() {")
    w("        this.resolved = null;")
    w("        this.resolvedLen = -1;")
    w("    }")
    w("")
    w("    // record.avsc, the schema text a Schema carries.")
    w("    public static #String definition() {")
    w(f"        return \"\" + \"{schema}\";")
    w("    }")
    w("")
    w("    public static #Schema schema() {")
    w("        String d #= WireRecordAvro.definition();")
    w("        int32 n = (int32) d.byteLength();")
    w("        int8[] b = heap int8[n];")
    w("        int32 i = 0;")
    w("        while (i < n) {")
    w("            b[i] = d.charAt(i);")
    w("            i = i + 1;")
    w("        }")
    w("        return heap Schema(#b);")
    w("    }")
    w("")
    w("    // The field-type letters of a definition: every \"type\": \"<t>\" value after")
    w("    // the first (the record's own), d/i/l for double/int/long, ? otherwise.")
    w("    static #String kindsOf(int8[] def) {")
    w("        String out = \"\";")
    w("        int32 n = (int32) def.count();")
    w("        int32 seen = 0;")
    w("        int32 i = 0;")
    w("        while (i + 7 < n) {")
    w("            if (def[i] == (int8) 34 && def[i + 1] == (int8) 116 && def[i + 2] == (int8) 121")
    w("                && def[i + 3] == (int8) 112 && def[i + 4] == (int8) 101 && def[i + 5] == (int8) 34) {")
    w("                int32 j = i + 6;")
    w("                while (j < n && def[j] != (int8) 34) {")
    w("                    j = j + 1;")
    w("                }")
    w("                j = j + 1;")
    w("                if (seen > 0 && j < n) {")
    w("                    int8 c = def[j];")
    w("                    if (c == (int8) 100) {")
    w("                        out = out + \"d\";")
    w("                    } else if (c == (int8) 105) {")
    w("                        out = out + \"i\";")
    w("                    } else if (c == (int8) 108) {")
    w("                        out = out + \"l\";")
    w("                    } else {")
    w("                        out = out + \"?\";")
    w("                    }")
    w("                }")
    w("                seen = seen + 1;")
    w("                i = j;")
    w("            } else {")
    w("                i = i + 1;")
    w("            }")
    w("        }")
    w("        return #out;")
    w("    }")
    w("")
    w("    void resolve(Schema schema) {")
    w("        int8[] def = schema.definition();")
    w("        if (this.resolvedLen == (int32) def.count()) {")
    w("            return;")
    w("        }")
    w("        String k #= WireRecordAvro.kindsOf(def);")
    w("        String want #= WireRecordAvro.kinds();")
    w("        if (k.equals(want) == false) {")
    w("            throw heap Exception(\"WireRecordAvro: the schema's field types do not match WireRecord\");")
    w("        }")
    w("        this.resolvedLen = (int32) def.count();")
    w("    }")
    w("")
    w("    static int32 vlen(int64 v) {")
    w("        int32 n = 1;")
    w("        int64 x = v;")
    w("        while (x >= (int64) 128) {")
    w("            x = x >> 7;")
    w("            n = n + 1;")
    w("        }")
    w("        return n;")
    w("    }")
    w("")
    w("    // zigzag of a non-negative v is 2v; a negative v is -2v - 1.")
    w("    static int64 zz(int64 v) {")
    w("        if (v < (int64) 0) {")
    w("            return ((0 - v) << 1) - (int64) 1;")
    w("        }")
    w("        return v << 1;")
    w("    }")
    w("")
    w("    static int64 unzz(int64 z) {")
    w("        if ((z & (int64) 1) == (int64) 0) {")
    w("            return z >> 1;")
    w("        }")
    w("        return 0 - ((z + (int64) 1) >> 1);")
    w("    }")
    w("")
    w("    public #int8[] encode(WireRecord v, Schema schema) {")
    w("        this.resolve(schema);")
    nf = 8 * sum(1 for k in K if kind(k) == "f64")
    w(f"        int32 s = {nf};")
    for k in K:
        t = kind(k)
        if t != "f64":
            src = f"(int64) v.f{k}" if t == "i32" else f"v.f{k}"
            w(f"        s = s + WireRecordAvro.vlen(WireRecordAvro.zz({src}));")
    w("        int8[] b = heap int8[s];")
    w("        int32 p = 0;")
    for k in K:
        t = kind(k)
        if t == "f64":
            w(f"        Cajeta.storeU64(b, (int64) p, Cajeta.f64ToBits(v.f{k}));")
            w("        p = p + 8;")
        else:
            src = f"(int64) v.f{k}" if t == "i32" else f"v.f{k}"
            w(f"        p = WireRecordPb.putVar(b, p, WireRecordAvro.zz({src}));")
    w("        return #b;")
    w("    }")
    w("")
    w("    public #WireRecord decode(int8[] bytes, Schema schema) {")
    w("        this.resolve(schema);")
    w("        WireRecord o = heap WireRecord();")
    w("        int32 p = 0;")
    w("        int64 v = 0;")
    w("        int32 sh = 0;")
    w("        int64 c = 0;")
    for k in K:
        t = kind(k)
        if t == "f64":
            w(f"        o.f{k} = Cajeta.bitsToF64(Cajeta.loadU64(bytes, (int64) p));")
            w("        p = p + 8;")
        else:
            w("        v = 0;")
            w("        sh = 0;")
            w("        c = (int64) 128;")
            w("        while (c >= (int64) 128) {")
            w("            c = ((int64) bytes[p]) & (int64) 255;")
            w("            v = v | ((c & (int64) 127) << sh);")
            w("            sh = sh + 7;")
            w("            p = p + 1;")
            w("        }")
            if t == "i32":
                w(f"        o.f{k} = (int32) WireRecordAvro.unzz(v);")
            else:
                w(f"        o.f{k} = WireRecordAvro.unzz(v);")
    w("        return #o;")
    w("    }")
    w("}")
    return "\n".join(L) + "\n"


def gen_view():
    L = []
    w = L.append
    w("package bench.wire;")
    w("")
    w("// GENERATED by bench/scripts/gen_wire.py: do not edit. The zero-copy views of")
    w(f"// the fixed layout ({FIXED} bytes per record, little-endian, fields in order):")
    w("// WireRecordView overlays one record, WireBatch a u32 count and that many")
    w("// records back to back (a fixed-size element array: constant-stride access,")
    w("// no offset table, no decode).")
    w("@LittleEndian")
    w("view WireRecordView {")
    for k in K:
        w(f"    {cj_type(k)} f{k};")
    w("}")
    w("")
    w("@LittleEndian")
    w("view WireBatch {")
    w("    WireRecordView[] recs;")
    w("}")
    return "\n".join(L) + "\n"


def gen_expect(c):
    L = []
    w = L.append
    w("package bench.wire;")
    w("")
    w("// GENERATED by bench/scripts/gen_wire.py: do not edit. The constants every")
    w("// wire/ benchmark checks against (computed by the generator from the record")
    w("// description, independently of any codec), full and smoke sizes.")
    w("public final class WireExpect {")
    for key, v in c.items():
        name = "".join(p.capitalize() if i else p for i, p in enumerate(key.split("_")))
        w(f"    public static int64 {name}() {{ return {v}L; }}")
    w("}")
    return "\n".join(L) + "\n"


