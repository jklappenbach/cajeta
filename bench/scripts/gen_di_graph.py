#!/usr/bin/env python3
"""One description of the aot/di-graph-100-startup graph (bench/aot/Components.md,
benchmark-reference unit 13), generated for every framework the page names.

The graph: components C<L>_<j>, L = 0..9 (levels), j = 0..9. C<L>_<j> for L < 9
injects C<L+1>_<j> and C<L+1>_<(j+1)%10>; the root C0_0 also injects C0_1..C0_9.
Every component is a process singleton; every constructor increments one
process-global counter. value(C<L>_<j>) = (10L + j + 1) + the values of its
dependencies (recomputed on every call, no memo). A program builds the graph
through its framework, calls root.value() (the first injected call), prints
`components=<counter> value=<V>` and exits.

Writes (relative to the bench/ directory, argv[1], default ..):
    src/aot-digraph/                     Cajeta: @Component / @Inject (cajeta.aot)
    competitors/java/aot/spring/         Spring (component scan)
    competitors/java/aot/dagger/         Dagger (@Inject constructors, @Component interface)
    competitors/java/aot/guice/          Guice (@Inject constructors, @Singleton)
    competitors/go/aot/wire/             google/wire (wire.go; wire_gen.go is the wire tool's output)
    competitors/rust/aot/shaku/          shaku (derive Component, module!)
    competitors/cpp/aot/expect.txt       the expected line
and prints the expected line.
"""
import os
import sys

LEVELS = 10
WIDTH = 10


def name(l, j):
    return f"C{l}_{j}"


def deps(l, j):
    d = []
    if l < LEVELS - 1:
        d = [(l + 1, j), (l + 1, (j + 1) % WIDTH)]
    if (l, j) == (0, 0):
        d += [(0, k) for k in range(1, WIDTH)]
    return d


NODES = [(l, j) for l in range(LEVELS) for j in range(WIDTH)]


def value(l, j):
    return 10 * l + j + 1 + sum(value(*d) for d in deps(l, j))


V = value(0, 0)
EXPECT = f"components={len(NODES)} value={V}"
HEAD = "GENERATED by bench/scripts/gen_di_graph.py: do not edit."


def cajeta():
    out = {}
    out["cajeta.json"] = f"""{{
    // {HEAD}
    // aot/di-graph-100-startup (bench/aot/Components.md): the 100-component
    // graph, 10 deep, as cajeta.aot @Component / @Inject classes. The harness
    // (bench/src/main/cajeta/bench/aot/) builds this project to an executable and
    // times its start-up to the first injected call. Build from this directory:
    //   cajeta release   -> build/aot-digraph
    "details": {{
        "name":                "aot-digraph",
        "version":             "0.1.0",
        "description":         "aot/di-graph-100-startup: a 100-component DI graph",
        "license":             "Apache-2.0",
        "authors":             ["cajeta"],
        "cajeta-lang-version": "1.0"
    }},
    "settings": {{
        "capabilities": [],
        "dependencies": {{}},
        "build": {{
            "source-root":  "src",
            "target":       "host",
            "entry-method": "digraph.Main::main"
        }}
    }},
    "tasks": {{
        "release": {{
            "description": "Optimized build (the bench harness's flavor) to build/aot-digraph",
            "actions": [
                {{ "action": "build",
                  "flavor": {{ "base": "release", "opt": "O3", "cpu": "native" }},
                  "output-path": "build/aot-digraph", "id": "art" }}
            ],
            "outputs": {{ "path": "${{art.path}}", "sha256": "${{art.sha256}}" }}
        }}
    }}
}}
"""
    L = ["package digraph;", "", "import cajeta.aot.Component;", "import cajeta.aot.Inject;", "",
         f"// {HEAD}", "// The 100 components (singletons). Each constructor counts itself.", "",
         "public final class Counter {", "    public static int32 n = 0;", "}", ""]
    for (l, j) in NODES:
        L.append(f"@Component public class {name(l, j)} {{")
        for i, d in enumerate(deps(l, j)):
            L.append(f"    @Inject {name(*d)} d{i};")
        L.append(f"    public {name(l, j)}() {{")
        L.append("        Counter.n = Counter.n + 1;")
        L.append("        return;")
        L.append("    }")
        terms = " + ".join([f"(int64) {10 * l + j + 1}"] + [f"this.d{i}.value()" for i in range(len(deps(l, j)))])
        L.append(f"    public int64 value() {{ return {terms}; }}")
        L.append("}")
        L.append("")
    out["src/digraph/Graph.cajeta"] = "\n".join(L)
    out["src/digraph/Main.cajeta"] = f"""package digraph;

// {HEAD}
// Resolve the root through the compile-time graph, make the first injected
// call, print `components=<constructed> value=<root.value()>`.
public final class Main {{
    public static int32 main(String[] args) {{
        C0_0 root = C0_0.__cajeta_inject();
        int64 v = root.value();
        System.stdout.println("components=" + Counter.n + " value=" + v);
        return 0;
    }}
}}
"""
    return out


def java_graph(style):
    """style: spring | dagger | guice."""
    L = ["package digraph;", ""]
    if style == "spring":
        L += ["import org.springframework.stereotype.Component;", ""]
    else:
        L += ["import jakarta.inject.Inject;", "import jakarta.inject.Singleton;", ""]
    L += [f"// {HEAD}", "", "final class Counter {", "    static int n = 0;", "}", ""]
    for (l, j) in NODES:
        n = name(l, j)
        ds = deps(l, j)
        ann = "@Component" if style == "spring" else "@Singleton"
        L.append(f"{ann}")
        L.append(f"class {n} {{")
        for i, d in enumerate(ds):
            L.append(f"    final {name(*d)} d{i};")
        params = ", ".join(f"{name(*d)} d{i}" for i, d in enumerate(ds))
        inj = "" if style == "spring" else "@Inject "
        L.append(f"    {inj}{n}({params}) {{")
        for i, _ in enumerate(ds):
            L.append(f"        this.d{i} = d{i};")
        L.append("        Counter.n++;")
        L.append("    }")
        terms = " + ".join([f"{10 * l + j + 1}L"] + [f"d{i}.value()" for i in range(len(ds))])
        L.append(f"    long value() {{ return {terms}; }}")
        L.append("}")
        L.append("")
    return "\n".join(L)


def java():
    out = {}
    out["spring/src/digraph/Graph.java"] = java_graph("spring")
    out["spring/src/digraph/Main.java"] = f"""package digraph;

import org.springframework.context.annotation.AnnotationConfigApplicationContext;

// {HEAD} Spring: component scan of the package, then the root bean's first call.
public final class Main {{
    public static void main(String[] args) {{
        try (AnnotationConfigApplicationContext ctx = new AnnotationConfigApplicationContext("digraph")) {{
            C0_0 root = ctx.getBean(C0_0.class);
            long v = root.value();
            System.out.println("components=" + Counter.n + " value=" + v);
        }}
    }}
}}
"""
    out["dagger/src/digraph/Graph.java"] = java_graph("dagger")
    out["dagger/src/digraph/Main.java"] = f"""package digraph;

import jakarta.inject.Singleton;

// {HEAD} Dagger: the component interface; DaggerAppGraph is generated by the
// annotation processor at build time.
public final class Main {{
    @Singleton
    @dagger.Component
    interface AppGraph {{
        C0_0 root();
    }}

    public static void main(String[] args) {{
        C0_0 root = DaggerMain_AppGraph.create().root();
        long v = root.value();
        System.out.println("components=" + Counter.n + " value=" + v);
    }}
}}
"""
    out["guice/src/digraph/Graph.java"] = java_graph("guice")
    out["guice/src/digraph/Main.java"] = f"""package digraph;

import com.google.inject.Guice;
import com.google.inject.Injector;

// {HEAD} Guice: just-in-time bindings from the @Inject constructors (no module).
public final class Main {{
    public static void main(String[] args) {{
        Injector inj = Guice.createInjector();
        C0_0 root = inj.getInstance(C0_0.class);
        long v = root.value();
        System.out.println("components=" + Counter.n + " value=" + v);
    }}
}}
"""
    return out


def go():
    out = {}
    L = ["package main", "", f"// {HEAD}", "", "var counter = 0", ""]
    for (l, j) in NODES:
        n = name(l, j)
        ds = deps(l, j)
        L.append(f"type {n} struct {{")
        for i, d in enumerate(ds):
            L.append(f"\td{i} *{name(*d)}")
        L.append("}")
        L.append("")
        params = ", ".join(f"d{i} *{name(*d)}" for i, d in enumerate(ds))
        args = ", ".join(f"d{i}" for i in range(len(ds)))
        L.append(f"func New{n}({params}) *{n} {{")
        L.append("\tcounter++")
        L.append(f"\treturn &{n}{{{args}}}")
        L.append("}")
        L.append("")
        terms = " + ".join([f"int64({10 * l + j + 1})"] + [f"c.d{i}.Value()" for i in range(len(ds))])
        L.append(f"func (c *{n}) Value() int64 {{ return {terms} }}")
        L.append("")
    out["graph.go"] = "\n".join(L)
    provs = ",\n\t\t".join(f"New{name(l, j)}" for (l, j) in NODES)
    out["wire.go"] = f"""//go:build wireinject
// +build wireinject

package main

// {HEAD} The injector wire generates wire_gen.go from.

import "github.com/google/wire"

func InitRoot() *C0_0 {{
\twire.Build(
\t\t{provs},
\t)
\treturn nil
}}
"""
    out["main.go"] = f"""package main

// {HEAD}

import "fmt"

func main() {{
\troot := InitRoot()
\tv := root.Value()
\tfmt.Printf("components=%d value=%d\\n", counter, v)
}}
"""
    return out


def rust():
    L = ["#![allow(non_camel_case_types, non_snake_case)]", f"// {HEAD}",
         "// shaku: one interface trait per component, derive(Component), one module.",
         "use shaku::{module, Component, HasComponent, Interface};",
         "use std::sync::atomic::{AtomicUsize, Ordering};", "use std::sync::Arc;", "",
         "static COUNTER: AtomicUsize = AtomicUsize::new(0);",
         "fn count() -> u8 { COUNTER.fetch_add(1, Ordering::SeqCst); 0 }", ""]
    for (l, j) in NODES:
        n = name(l, j)
        ds = deps(l, j)
        L.append(f"pub trait I{n}: Interface {{ fn value(&self) -> i64; }}")
        L.append("#[derive(Component)]")
        L.append(f"#[shaku(interface = I{n})]")
        L.append(f"pub struct {n} {{")
        for i, d in enumerate(ds):
            L.append("    #[shaku(inject)]")
            L.append(f"    d{i}: Arc<dyn I{name(*d)}>,")
        L.append("    #[shaku(default = count())]")
        L.append("    _c: u8,")
        L.append("}")
        terms = " + ".join([f"{10 * l + j + 1}i64"] + [f"self.d{i}.value()" for i in range(len(ds))])
        L.append(f"impl I{n} for {n} {{ fn value(&self) -> i64 {{ {terms} }} }}")
        L.append("")
    comps = ", ".join(name(l, j) for (l, j) in NODES)
    L.append("module! {")
    L.append("    Graph {")
    L.append(f"        components = [{comps}],")
    L.append("        providers = []")
    L.append("    }")
    L.append("}")
    L.append("")
    L.append("fn main() {")
    L.append("    let m = Graph::builder().build();")
    L.append("    let root: &dyn IC0_0 = m.resolve_ref();")
    L.append("    let v = root.value();")
    L.append('    println!("components={} value={}", COUNTER.load(Ordering::SeqCst), v);')
    L.append("}")
    return {"src/main.rs": "\n".join(L) + "\n"}


def write(base, files):
    for rel, s in files.items():
        p = os.path.join(base, rel)
        os.makedirs(os.path.dirname(p), exist_ok=True)
        with open(p, "w") as f:
            f.write(s)


def main():
    root = sys.argv[1] if len(sys.argv) > 1 else os.path.join(os.path.dirname(__file__), "..")
    write(os.path.join(root, "src/aot-digraph"), cajeta())
    write(os.path.join(root, "competitors/java/aot"), java())
    write(os.path.join(root, "competitors/go/aot/wire"), go())
    write(os.path.join(root, "competitors/rust/aot/shaku"), rust())
    write(os.path.join(root, "competitors/cpp/aot"), {"expect.txt": EXPECT + "\n"})
    print(EXPECT)


if __name__ == "__main__":
    main()
