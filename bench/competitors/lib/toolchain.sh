#!/usr/bin/env bash
# Shared by the toolchain/ drivers (competitors/drivers/toolchain/*.sh, spec §6.14).
# Sourced, not run: run.sh only runs drivers/<package>/*.sh, and this lives in lib/.
#
# Every toolchain row times a command with python/toolchain/cmdbench.py, the
# same fork/exec/wait region dev.cajeta.bench's ExternalBenchmark times on the
# Cajeta side, and prints one v1 row that run.sh's rows_v2 lifts to v2.
#
# Provides: TC (competitors/), BENCH (bench/), REPO (CAJETA_BENCH_REPO, else bench/..), W (work dir, gitignored),
# PY (the venv python, else /usr/bin/python3), cb (cmdbench), skip_row, the
# version strings, synth_tree (the compile-10k program, generated by
# datasets/gen_synth.py into datasets/cache/), and NPROC.

TC="$( cd -- "$( dirname -- "${BASH_SOURCE[0]}" )/.." &> /dev/null && pwd )"
BENCH="$( cd -- "$TC/.." &> /dev/null && pwd )"
REPO="${CAJETA_BENCH_REPO:-$( cd -- "$BENCH/.." &> /dev/null && pwd )}"
W="${CAJETA_BENCH_TOOLCHAIN_COMP_WORK:-$TC/.build/toolchain}"
mkdir -p "$W"
export PATH="$HOME/.cargo/bin:$TC/bin:$PATH"
NPROC="$(nproc 2>/dev/null || echo 4)"

PY="$TC/python/.venv/bin/python"
[[ -x "$PY" ]] || PY="$(command -v python3)"
# CPython as shipped, for the rows that measure CPython itself (not the venv,
# whose site-packages a start-up row should not pay for).
CPY="/usr/bin/python3"
[[ -x "$CPY" ]] || CPY="$(command -v python3)"

LLVM_BIN="${CAJETA_LLVM_BIN:-$REPO/../cajeta-llvm/llvm-install/bin}"

strip_c() { tr -d ',"' | head -1; }
V_GXX="$(g++ --version 2>/dev/null | strip_c)"
V_RUSTC="$(rustc --version 2>/dev/null | strip_c)"
V_CARGO="$(cargo --version 2>/dev/null | strip_c)"
V_GO="$(go version 2>/dev/null | strip_c)"
V_JAVA="$(java -version 2>&1 | strip_c)"
V_JAVAC="$(javac -version 2>&1 | strip_c)"
V_CPY="$("$CPY" --version 2>&1 | strip_c)"
V_NINJA="$(ninja --version 2>/dev/null | strip_c)"
V_CLANG="$("$LLVM_BIN/clang++" --version 2>/dev/null | strip_c)"

cb() { "$PY" "$TC/python/toolchain/cmdbench.py" "$@"; }

# skip_row <slug> <lang> <library> <reason> [variant]
skip_row() { cb --bench "$1" --lang "$2" --library "$3" --variant "${5:-}" --skip "$4"; }

# The compile-10k program in every language; prints its root
# (<bench>/datasets/cache/synth-10k with cajeta/ java/ rust/ go/ cpp/ python/,
# EXPECTED and LINES). Regenerated only when gen_synth.py changes.
synth_tree() { "$CPY" "$BENCH/datasets/gen_synth.py" "$BENCH/datasets/cache"; }

# fresh_copy <src> <dst>: <dst> becomes an exact copy of <src>.
fresh_copy() { rm -rf "$2" && mkdir -p "$(dirname "$2")" && cp -r "$1" "$2"; }
