#!/usr/bin/env python3
"""Generates the wire/ competitors' per-field code from the record description
in bench/scripts/gen_wire.py (f1..f100: k % 5 == 0 double, k % 5 == 1 int32,
else int64), so every language reads and writes the same 100 fields:

    cpp/wire/wire/wire_fields.h          X-macro list WIRE_FIELDS(X) -> X(k, kind)
    java/wire/wire/WireFields.java       protobuf-java fill/checksum, Avro GenericRecord fill/checksum
    rust/wire/wire/src/record.rs         the serde struct, fill and checksum

Run from anywhere: python3 competitors/cpp/wire/gen_competitors.py
"""
import os

HERE = os.path.dirname(os.path.abspath(__file__))
COMP = os.path.normpath(os.path.join(HERE, "..", ".."))
K = range(1, 101)


def kind(k):
    return "f64" if k % 5 == 0 else ("i32" if k % 5 == 1 else "i64")


def cpp():
    lines = ["// GENERATED by competitors/cpp/wire/gen_competitors.py: do not edit.",
             "// The wire/ record's fields: X(k, kind), kind one of F64, I32, I64.",
             "#pragma once", "#define WIRE_FIELDS(X) \\"]
    for k in K:
        lines.append(f"    X({k}, {kind(k).upper()}){' \\' if k < 100 else ''}")
    return "\n".join(lines) + "\n"


def jval(k):
    t = kind(k)
    if t == "f64":
        return f"r * 0.5 + {k * 0.25!r}"
    if t == "i32":
        return f"(r * 31 + {k * 17}) % 65536"
    return f"(long) (r + 1) * {k * k * k + 17}L"


def java():
    L = ["// GENERATED by competitors/cpp/wire/gen_competitors.py: do not edit.",
         "import org.apache.avro.Schema;", "import org.apache.avro.generic.GenericData;",
         "import org.apache.avro.generic.GenericRecord;", "",
         "final class WireFields {",
         "    static benchwire.RecordProto.WireRecord pbFill(int r) {",
         "        return benchwire.RecordProto.WireRecord.newBuilder()"]
    for k in K:
        L.append(f"            .setF{k}({jval(k)})")
    L += ["            .build();", "    }", "",
          "    static long pbSum(benchwire.RecordProto.WireRecord m) {", "        long s = 0;"]
    for k in K:
        L.append(f"        s += (long) (m.getF{k}() * 4.0);" if kind(k) == "f64" else f"        s += m.getF{k}();")
    L += ["        return s;", "    }", "",
          "    // Avro: fields by position (schema order f1..f100).",
          "    static GenericRecord avroFill(Schema schema, int r) {",
          "        GenericData.Record g = new GenericData.Record(schema);"]
    for k in K:
        t = kind(k)
        box = {"f64": "Double.valueOf", "i32": "Integer.valueOf", "i64": "Long.valueOf"}[t]
        L.append(f"        g.put({k - 1}, {box}({jval(k)}));")
    L += ["        return g;", "    }", "",
          "    static long avroSum(GenericRecord g) {", "        long s = 0;"]
    for k in K:
        t = kind(k)
        if t == "f64":
            L.append(f"        s += (long) (((Double) g.get({k - 1})) * 4.0);")
        elif t == "i32":
            L.append(f"        s += (Integer) g.get({k - 1});")
        else:
            L.append(f"        s += (Long) g.get({k - 1});")
    L += ["        return s;", "    }", "}"]
    return "\n".join(L) + "\n"


def rust():
    t = {"f64": "f64", "i32": "i32", "i64": "i64"}
    L = ["// GENERATED by competitors/cpp/wire/gen_competitors.py: do not edit.",
         "use serde::{Deserialize, Serialize};", "",
         "#[derive(Serialize, Deserialize, Clone, Debug, PartialEq)]", "pub struct WireRecord {"]
    for k in K:
        L.append(f"    pub f{k}: {t[kind(k)]},")
    L += ["}", "", "impl WireRecord {", "    pub fn fill(r: i64) -> WireRecord {", "        WireRecord {"]
    for k in K:
        tk = kind(k)
        if tk == "f64":
            v = f"r as f64 * 0.5 + {k * 0.25!r}"
        elif tk == "i32":
            v = f"((r * 31 + {k * 17}) % 65536) as i32"
        else:
            v = f"(r + 1) * {k * k * k + 17}"
        L.append(f"            f{k}: {v},")
    L += ["        }", "    }", "", "    pub fn checksum(&self) -> i64 {", "        let mut s: i64 = 0;"]
    for k in K:
        tk = kind(k)
        if tk == "f64":
            L.append(f"        s += (self.f{k} * 4.0) as i64;")
        elif tk == "i32":
            L.append(f"        s += self.f{k} as i64;")
        else:
            L.append(f"        s += self.f{k};")
    L += ["        s", "    }", "}"]
    return "\n".join(L) + "\n"


def main():
    out = {
        os.path.join(COMP, "cpp/wire/wire/wire_fields.h"): cpp(),
        os.path.join(COMP, "java/wire/wire/WireFields.java"): java(),
        os.path.join(COMP, "rust/wire/wire/src/record.rs"): rust(),
    }
    for p, s in out.items():
        os.makedirs(os.path.dirname(p), exist_ok=True)
        with open(p, "w") as f:
            f.write(s)
        print("wrote", os.path.relpath(p, COMP))


if __name__ == "__main__":
    main()
